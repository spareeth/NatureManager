"""Compute a site grid from a boundary GeoJSON and write the site seed SQL.

Rule (docs/COORDINATES.md section 1): origin = south-west corner of the boundary bounding box in
EPSG:3997, rounded down to the whole metre, minus 10 m on each axis. Rotation 0, scale 1.

    python scripts/setup_site_grid.py                     # writes supabase/seed/02_site_tg.sql
    python scripts/setup_site_grid.py --print             # show the grid only
"""

from __future__ import annotations

import argparse
import json
import math
from dataclasses import dataclass
from pathlib import Path

from pyproj import Transformer

ROOT = Path(__file__).resolve().parents[1]
MARGIN_M = 10.0

# CRS84 (lon, lat) -> EPSG:3997 (easting, northing), always x/y order.
_to_3997 = Transformer.from_crs("OGC:CRS84", "EPSG:3997", always_xy=True)


@dataclass(frozen=True)
class Grid:
    origin_e: float
    origin_n: float
    extent_x: float
    extent_y: float


def _coords(geometry: dict) -> list[tuple[float, float]]:
    if geometry["type"] == "Polygon":
        polys = [geometry["coordinates"]]
    elif geometry["type"] == "MultiPolygon":
        polys = geometry["coordinates"]
    else:
        raise ValueError(f"boundary must be a Polygon or MultiPolygon, got {geometry['type']}")
    return [(x, y) for poly in polys for ring in poly for x, y, *_ in ring]


def load_boundary(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    crs = data.get("crs", {}).get("properties", {}).get("name", "urn:ogc:def:crs:OGC:1.3:CRS84")
    if not crs.endswith("CRS84"):
        raise ValueError(f"expected CRS84 GeoJSON, got {crs}")
    features = data["features"] if data["type"] == "FeatureCollection" else [data]
    if len(features) != 1:
        raise ValueError(f"expected one boundary feature, got {len(features)}")
    return features[0]["geometry"]


def compute_grid(geometry: dict) -> Grid:
    pts = [_to_3997.transform(x, y) for x, y in _coords(geometry)]
    min_e = min(e for e, _ in pts)
    min_n = min(n for _, n in pts)
    max_e = max(e for e, _ in pts)
    max_n = max(n for _, n in pts)
    origin_e = math.floor(min_e) - MARGIN_M
    origin_n = math.floor(min_n) - MARGIN_M
    return Grid(origin_e, origin_n, max_e - origin_e, max_n - origin_n)


def site_sql(geometry: dict, grid: Grid, *, org_slug: str, code: str, name: str,
             site_type: str, grid_name: str, source: str) -> str:
    gj = json.dumps(geometry, separators=(",", ":"))

    def q(s: str) -> str:
        return "'" + s.replace("'", "''") + "'"

    return f"""-- Generated by scripts/setup_site_grid.py from {source}. Do not edit by hand.
-- Grid: origin E {grid.origin_e:.0f}, N {grid.origin_n:.0f} (EPSG:3997), rotation 0, scale 1;
-- site spans about x 0 to {grid.extent_x:.0f} m, y 0 to {grid.extent_y:.0f} m.
insert into site (organisation_id, code, name, site_type, boundary, grid_name,
                  grid_origin_e, grid_origin_n, grid_rotation_deg, grid_scale)
select o.id, {q(code)}, {q(name)}, {q(site_type)},
       st_multi(st_setsrid(st_geomfromgeojson({q(gj)}), 4326)),
       {q(grid_name)}, {grid.origin_e:.0f}, {grid.origin_n:.0f}, 0, 1
from organisation o where o.slug = {q(org_slug)};
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--boundary", type=Path, default=ROOT / "data/gis/TG_boundary.geojson")
    ap.add_argument("--out", type=Path, default=ROOT / "supabase/seed/02_site_tg.sql")
    ap.add_argument("--org", default="terra")
    ap.add_argument("--code", default="TG")
    ap.add_argument("--name", default="Terra Garden")
    ap.add_argument("--site-type", default="botanical_garden")
    ap.add_argument("--grid-name", default="Terra Garden Grid 2026")
    ap.add_argument("--print", action="store_true", help="print the grid and do not write SQL")
    args = ap.parse_args()

    geometry = load_boundary(args.boundary)
    grid = compute_grid(geometry)
    print(f"origin E {grid.origin_e:.0f}, N {grid.origin_n:.0f}; "
          f"extent x {grid.extent_x:.1f} m, y {grid.extent_y:.1f} m")
    if args.print:
        return
    source = args.boundary.resolve().relative_to(ROOT).as_posix()
    args.out.write_text(site_sql(geometry, grid, org_slug=args.org, code=args.code, name=args.name,
                                 site_type=args.site_type, grid_name=args.grid_name, source=source),
                        encoding="utf-8")
    print(f"wrote {args.out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
