"""Validate a bed layer (GeoJSON) and write the location seed SQL (task 1.1, FR-SITE-04).

Beds come from the GeoJSON; zones are made in PostGIS by dissolving beds on their code prefix
(docs/HORTIS_MIGRATION.md step 1). Validation runs first and nothing is written if it fails:
CRS84, valid polygons, code pattern, unique codes, every bed inside the site boundary, and the
codes equal the Hortis location names (when the raw export is present).

    python scripts/import_locations.py              # writes supabase/seed/05_locations_tg.sql
    python scripts/import_locations.py --check      # validate only
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from pyproj import Transformer
from shapely.geometry import shape
from shapely.ops import transform as shp_transform

ROOT = Path(__file__).resolve().parents[1]
CODE_RE = re.compile(r"^(?P<zone>[A-Z]{2})-(?P<n>\d{2})$")
# Zone names from the tag standard (docs/DATA_MODEL.md: "WG07 = West Garden bed 07").
ZONES = {"EG": "East Garden", "NG": "North Garden", "SG": "South Garden", "WG": "West Garden"}
# Bed outlines may touch the boundary line; allow 1 cm of drawing tolerance.
BOUNDARY_TOLERANCE_M = 0.01
_to_3997 = Transformer.from_crs("OGC:CRS84", "EPSG:3997", always_xy=True).transform


@dataclass(frozen=True)
class Bed:
    code: str
    zone: str
    geometry: dict  # GeoJSON, CRS84
    area_m2: float  # EPSG:3997


def _crs(data: dict) -> str:
    return data.get("crs", {}).get("properties", {}).get("name", "urn:ogc:def:crs:OGC:1.3:CRS84")


def load_beds(path: Path, name_field: str = "Name") -> list[Bed]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not _crs(data).endswith("CRS84"):
        raise ValueError(f"{path.name}: expected CRS84, got {_crs(data)}")
    beds = []
    for f in data["features"]:
        code = str(f["properties"].get(name_field, "")).strip()
        m = CODE_RE.match(code)
        beds.append(Bed(code, m["zone"] if m else "", f["geometry"],
                        shp_transform(_to_3997, shape(f["geometry"])).area))
    return beds


def load_boundary(path: Path):
    data = json.loads(path.read_text(encoding="utf-8"))
    if not _crs(data).endswith("CRS84"):
        raise ValueError(f"{path.name}: expected CRS84, got {_crs(data)}")
    return shp_transform(_to_3997, shape(data["features"][0]["geometry"]))


def hortis_locations(materials: Path) -> set[str] | None:
    if not materials.exists():
        return None
    with materials.open(encoding="utf-8-sig", newline="") as f:
        return {row["Location name"].strip() for row in csv.DictReader(f)}


def validate(beds: list[Bed], boundary, hortis: set[str] | None) -> list[str]:
    """Return a list of problems; empty means the layer can be imported."""
    problems = []
    seen: dict[str, int] = {}
    for i, b in enumerate(beds):
        where = f"feature {i} ({b.code or 'no code'})"
        if not CODE_RE.match(b.code):
            problems.append(f"{where}: code does not match ZZ-NN")
        elif b.zone not in ZONES:
            problems.append(f"{where}: unknown zone prefix {b.zone}")
        if b.code in seen:
            problems.append(f"{where}: duplicate code, also feature {seen[b.code]}")
        seen.setdefault(b.code, i)
        if b.geometry["type"] not in ("Polygon", "MultiPolygon"):
            problems.append(f"{where}: geometry is {b.geometry['type']}, expected a polygon")
            continue
        g = shp_transform(_to_3997, shape(b.geometry))
        if not g.is_valid:
            problems.append(f"{where}: invalid geometry")
        elif g.area <= 0:
            problems.append(f"{where}: empty geometry")
        elif not boundary.buffer(BOUNDARY_TOLERANCE_M).covers(g):
            problems.append(f"{where}: not inside the site boundary")
    if hortis is not None:
        codes = {b.code for b in beds}
        for c in sorted(hortis - codes):
            problems.append(f"Hortis location {c} has no bed polygon")
        for c in sorted(codes - hortis):
            problems.append(f"bed {c} is not a Hortis location name")
    return problems


def seed_sql(beds: list[Bed], *, org_slug: str, site_code: str, source: str) -> str:
    def q(s: str) -> str:
        return "'" + s.replace("'", "''") + "'"

    rows = ",\n".join(
        f"  ({q(b.code)}, {q(b.zone)}, {q(json.dumps(b.geometry, separators=(',', ':')))})"
        for b in sorted(beds, key=lambda b: b.code))
    zones = ",\n".join(f"  ({q(k)}, {q(v)})" for k, v in ZONES.items()
                       if any(b.zone == k for b in beds))
    return f"""-- Generated by scripts/import_locations.py from {source}. Do not edit by hand.
-- {len(beds)} beds; zones are the dissolved beds of each code prefix.
create temp table seed_bed (code text, zone text, geojson text) on commit drop;
insert into seed_bed values
{rows};

create temp table seed_zone (code text, name text) on commit drop;
insert into seed_zone values
{zones};

-- Zones: union of their beds.
insert into location (organisation_id, site_id, kind, code, name, geom)
select s.organisation_id, s.id, 'zone', z.code, z.name,
       st_multi(st_union(st_setsrid(st_geomfromgeojson(b.geojson), 4326)))
from seed_zone z
join seed_bed b on b.zone = z.code
join site s on s.code = {q(site_code)}
join organisation o on o.id = s.organisation_id and o.slug = {q(org_slug)}
group by s.organisation_id, s.id, z.code, z.name;

-- Beds, each under its zone. Codes are the Hortis location names.
insert into location (organisation_id, site_id, parent_id, kind, code, name, geom)
select s.organisation_id, s.id, z.id, 'bed', b.code, b.code,
       st_multi(st_setsrid(st_geomfromgeojson(b.geojson), 4326))
from seed_bed b
join site s on s.code = {q(site_code)}
join organisation o on o.id = s.organisation_id and o.slug = {q(org_slug)}
join location z on z.site_id = s.id and z.kind = 'zone' and z.code = b.zone;
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--beds", type=Path, default=ROOT / "data/gis/TG_beds_new.geojson")
    ap.add_argument("--boundary", type=Path, default=ROOT / "data/gis/TG_boundary.geojson")
    ap.add_argument("--hortis", type=Path, default=ROOT / "data/hortis/raw/2026-04-27/materials.csv")
    ap.add_argument("--out", type=Path, default=ROOT / "supabase/seed/05_locations_tg.sql")
    ap.add_argument("--org", default="terra")
    ap.add_argument("--site", default="TG")
    ap.add_argument("--check", action="store_true", help="validate only, do not write SQL")
    args = ap.parse_args()

    beds = load_beds(args.beds)
    hortis = hortis_locations(args.hortis)
    problems = validate(beds, load_boundary(args.boundary), hortis)
    if problems:
        print(f"{len(problems)} problem(s), nothing written:")
        for p in problems:
            print("  " + p)
        return 1

    per_zone: dict[str, list[Bed]] = {}
    for b in beds:
        per_zone.setdefault(b.zone, []).append(b)
    if hortis is None:
        print(f"{len(beds)} beds valid; warning: {args.hortis} not found, Hortis name check skipped")
    else:
        print(f"{len(beds)} beds valid; codes equal the {len(hortis)} Hortis location names")
    for z, bs in sorted(per_zone.items()):
        print(f"  {z} {ZONES[z]}: {len(bs)} beds, {sum(b.area_m2 for b in bs):,.0f} m2")
    print(f"  total {sum(b.area_m2 for b in beds):,.0f} m2")
    if args.check:
        return 0
    source = args.beds.resolve().relative_to(ROOT).as_posix()
    args.out.write_text(seed_sql(beds, org_slug=args.org, site_code=args.site, source=source), encoding="utf-8")
    print(f"wrote {args.out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
